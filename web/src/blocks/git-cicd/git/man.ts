// Offline Git manual pages (the subset the course needs). Text follows the
// official pages at git-scm.com/docs (GPL-2.0), shortened to the options the
// simulator implements; each page keeps the real anatomy: NAME, SYNOPSIS,
// DESCRIPTION, OPTIONS, EXAMPLES, SEE ALSO.

import type { DocPage } from '../../../core/types';

const page = (name: string, oneLine: string, synopsis: string, description: string, options: string, examples: string, seeAlso: string, section = 1): DocPage => ({
  id: `man/${name}.${section}`,
  source: 'git-help',
  title: `${name}(${section})`,
  url: `https://git-scm.com/docs/${name}`,
  license: 'GPL-2.0',
  version: 'git 2.52',
  sections: [
    { id: 'NAME', body: `${name} - ${oneLine}` },
    { id: 'SYNOPSIS', body: synopsis },
    { id: 'DESCRIPTION', body: description },
    ...(options ? [{ id: 'OPTIONS', body: options }] : []),
    ...(examples ? [{ id: 'EXAMPLES', body: examples }] : []),
    { id: 'SEE ALSO', body: seeAlso },
  ],
});

