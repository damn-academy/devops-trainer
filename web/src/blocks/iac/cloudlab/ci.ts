// The CI bridge of the in-tab lab (design 00 §6.13): a push to git.lab starts
// a pipeline from the pushed commit's .gitlab-ci.yml, and its jobs run as
// shell scripts on a real lab machine, the way gitlab-runner does with the
// shell executor: clone the commit into a build directory, export the CI
// variables, run before_script and script with `set -e`, then after_script.
//
// The job runs in the background on the machine and is polled, so the
// machine's service channel stays free for fact collection. Parsing and
// rules come from the CI/CD block (git-cicd/ci/config.ts), so the same YAML
// behaves the same in the simulator and on real machines.

import { decide, parseCi, type CiJob } from '../../git-cicd/ci/config';
import type { GitServer, PushInfo } from '../../../engine/labhost/git/server';
import type { GitStore } from '../../../engine/labhost/git/store';
import type { HttpRequest, HttpResponse } from '../../../engine/labhost/http';
import type { CiJobFacts, CiPipelineFacts, CiScope } from './facts';

export interface Runner {
  exec(cmd: string): Promise<{ out: string; exit: number }>;
}

export type JobStatus = 'created' | 'pending' | 'running' | 'success' | 'failed' | 'skipped' | 'manual' | 'canceled';
export type PipelineStatus = 'pending' | 'running' | 'success' | 'failed' | 'canceled';

export interface CiJobRun {
  id: number;
  name: string;
  stage: string;
  when: CiJob['when'];
  allowFailure: boolean;
  status: JobStatus;
  exit?: number;
  log: string;
  started?: number;
  finished?: number;
  job: CiJob;
}

export interface CiPipeline {
  id: number;
  repo: string;
  ref: string;
  sha: string;
  status: PipelineStatus;
  stages: string[];
  jobs: CiJobRun[];
  env: Record<string, string>;
  error?: string;
  created: number;
}

const q = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;
const EOF = 'DT_CI_EOF';
const LOG_TAIL = 60_000;

/** The shell script of one job (exported for tests). */
export function jobScript(p: Pick<CiPipeline, 'repo' | 'sha' | 'env'>, job: CiJob, dir: string, cloneUrl: string, artifactsDir: string): string {
  const art = job.artifacts?.paths ?? [];
  const vars = { TF_PLUGIN_CACHE_DIR: '/var/cache/lab-ci/providers', ...p.env, ...job.variables, CI_JOB_NAME: job.name, CI_JOB_STAGE: job.stage, CI_PROJECT_DIR: dir };
  const lines = [
    '#!/bin/sh',
    '# Generated by the lab CI bridge for one job (shell executor).',
    '[ -r /etc/profile ] && . /etc/profile >/dev/null 2>&1',
    ...Object.entries(vars).map(([k, v]) => `export ${k}=${q(v)}`),
    `echo ${q(`Running on $(hostname) (shell executor), ${p.repo} @ ${p.sha.slice(0, 8)}`)}`,
    // Reuse repository objects across jobs, but never reuse a dirty worktree or old artifacts.
    `if [ -d ${q(dir + '/.git')} ]; then git -C ${q(dir)} remote set-url origin ${q(cloneUrl)} && git -C ${q(dir)} fetch -q origin || exit 1; else rm -rf ${q(dir)} && git clone -q ${q(cloneUrl)} ${q(dir)} || { echo 'ERROR: git clone failed'; exit 1; }; fi`,
    `cd ${q(dir)} && git reset --hard -q ${q(p.sha)} && git clean -ffdx -q && git -c advice.detachedHead=false checkout -q ${q(p.sha)} || exit 1`,
    'mkdir -p "$TF_PLUGIN_CACHE_DIR" || exit 1',
    // Artifacts of earlier jobs of the pipeline (GitLab downloads them into the build directory).
    `if [ -d ${q(artifactsDir)} ]; then echo 'Downloading artifacts of earlier jobs'; cp -a ${q(artifactsDir)}/. . ; fi`,
    'dt_main() {',
    '  set -e',
    ...[...job.beforeScript, ...job.script].flatMap((l) => [`printf '%s\\n' ${q(`$ ${l.split('\n')[0]}${l.includes('\n') ? ' # collapsed multi-line command' : ''}`)}`, l]),
    '}',
    '( dt_main ); dt_rc=$?',
    ...(art.length
      ? [
          `if [ "$dt_rc" -eq 0 ] || [ ${q(job.artifacts?.when ?? 'on_success')} = always ]; then echo 'Uploading artifacts: ${art.join(' ').replace(/'/g, '')}'; mkdir -p ${q(artifactsDir)}; tar cf - ${art.map(q).join(' ')} 2>/dev/null | ( cd ${q(artifactsDir)} && tar xf - ); fi`,
        ]
      : []),
    ...(job.afterScript.length ? ['echo "Running after_script"', ...job.afterScript.flatMap((l) => [`printf '%s\\n' ${q(`$ ${l}`)}`, `( ${l} ) || true`])] : []),
    '[ "$dt_rc" -eq 0 ] && echo "Job succeeded" || echo "ERROR: Job failed: exit code $dt_rc"',
    'exit $dt_rc',
  ];
  return `${lines.join('\n')}\n`;
}

/** Files that differ between two commits (for rules: changes). */
function changedFiles(store: GitStore, repo: string, before: string | null, after: string): string[] {
  const a = before ? store.files(repo, before) : new Map<string, Uint8Array>();
  const b = store.files(repo, after);
  const out: string[] = [];
  const same = (x?: Uint8Array, y?: Uint8Array) => !!x && !!y && x.length === y.length && x.every((v, i) => v === y[i]);
  for (const [k, v] of b) if (!same(a.get(k), v)) out.push(k);
  for (const k of a.keys()) if (!b.has(k)) out.push(k);
  return out;
}

export class CiBridge {
  readonly pipelines: CiPipeline[] = [];
  private seq = 0;
  private jobSeq = 0;
  private fns = new Set<() => void>();
  private off: () => void;
  private queue: Promise<void> = Promise.resolve();
  private disposed = false;

  constructor(
    git: GitServer,
    private runner: () => Runner | null,
    private o: { pollMs?: number; jobTimeoutMs?: number; sleep?: (ms: number) => Promise<void> } = {},
  ) {
    this.off = git.onPush((info, store) => this.onPush(info, store));
  }

  on(fn: () => void): () => void {
    this.fns.add(fn);
    return () => this.fns.delete(fn);
  }

  private emit() {
    for (const f of this.fns) f();
  }

  private sleep(ms: number) {
    return this.o.sleep ? this.o.sleep(ms) : new Promise<void>((r) => setTimeout(r, ms));
  }

  /** Create the pipelines of a push; the jobs run in the background, one at a time (one runner). */
  onPush(info: PushInfo, store: GitStore): string[] {
    const lines: string[] = [];
    const repo = store.get(info.repo);
    for (const u of info.updates) {
      if (!u.after) continue;
      const isTag = u.ref.startsWith('refs/tags/');
      if (!isTag && !u.ref.startsWith('refs/heads/')) continue;
      const files = store.files(info.repo, u.after);
      const yml = files.get('.gitlab-ci.yml');
      if (!yml) continue;
      const name = u.ref.replace(/^refs\/(heads|tags)\//, '');
      const id = ++this.seq;
      const env: Record<string, string> = {
        CI: 'true',
        GITLAB_CI: 'true',
        CI_PIPELINE_ID: String(id),
        CI_PIPELINE_SOURCE: 'push',
        CI_COMMIT_SHA: u.after,
        CI_COMMIT_SHORT_SHA: u.after.slice(0, 8),
        CI_COMMIT_BEFORE_SHA: u.before ?? '0'.repeat(40),
        CI_COMMIT_REF_NAME: name,
        CI_COMMIT_REF_SLUG: name.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 63),
        CI_DEFAULT_BRANCH: (repo?.head ?? 'refs/heads/main').replace('refs/heads/', ''),
        CI_PROJECT_NAME: info.repo.split('/').pop()!,
        CI_PROJECT_PATH: info.repo,
        CI_REPOSITORY_URL: `http://git.lab/${info.repo}.git`,
        CI_SERVER_URL: 'http://git.lab',
        ...(isTag ? { CI_COMMIT_TAG: name } : { CI_COMMIT_BRANCH: name }),
      };
      const parsed = parseCi(new TextDecoder().decode(yml));
      const p: CiPipeline = { id, repo: info.repo, ref: name, sha: u.after, status: 'pending', stages: [], jobs: [], env, created: Date.now() };
      if (!parsed.config) {
        p.status = 'failed';
        p.error = `.gitlab-ci.yml is invalid: ${parsed.errors.map((e) => `line ${e.line}: ${e.message}`).join('; ')}`;
        this.pipelines.push(p);
        lines.push(`CI: pipeline #${id} failed: ${p.error}`);
        this.emit();
        continue;
      }
      Object.assign(env, { ...parsed.config.variables, ...env });
      const changed = changedFiles(store, info.repo, u.before, u.after);
      p.stages = parsed.config.stages;
      for (const job of parsed.config.jobs) {
        const d = decide(job, env, changed);
        if (!d.included) continue;
        p.jobs.push({ id: ++this.jobSeq, name: job.name, stage: job.stage, when: d.when, allowFailure: d.allowFailure, status: d.when === 'manual' ? 'manual' : 'created', log: '', job });
      }
      p.jobs.sort((a, b) => p.stages.indexOf(a.stage) - p.stages.indexOf(b.stage));
      if (!p.jobs.length) {
        lines.push(`CI: no jobs for ${name} (rules excluded every job)`);
        continue;
      }
      this.pipelines.push(p);
      lines.push(`CI: pipeline #${id} for ${name}: ${p.jobs.map((j) => j.name).join(', ')} — curl http://ci.lab/pipelines/${id}`);
      this.emit();
      this.enqueue(() => this.runPipeline(p));
    }
    return lines;
  }

  private enqueue(fn: () => Promise<void>) {
    this.queue = this.queue.then(fn).catch(() => undefined);
  }

  /** Start a manual job of a pipeline (the "play" button). */
  play(pipelineId: number, jobName: string): boolean {
    const p = this.pipelines.find((x) => x.id === pipelineId);
    const j = p?.jobs.find((x) => x.name === jobName && x.status === 'manual');
    if (!p || !j) return false;
    j.status = 'pending';
    p.status = 'running';
    this.emit();
    this.enqueue(async () => {
      await this.runJob(p, j);
      p.status = this.statusOf(p);
      this.emit();
    });
    return true;
  }

  private statusOf(p: CiPipeline): PipelineStatus {
    if (p.jobs.some((j) => j.status === 'running' || j.status === 'pending')) return 'running';
    if (p.jobs.some((j) => j.status === 'failed' && !j.allowFailure)) return 'failed';
    if (p.jobs.some((j) => j.status === 'canceled')) return 'canceled';
    return 'success';
  }

  private async runPipeline(p: CiPipeline): Promise<void> {
    p.status = 'running';
    this.emit();
    let failed = false;
    for (const stage of p.stages) {
      for (const j of p.jobs.filter((x) => x.stage === stage)) {
        if (this.disposed) return;
        if (j.status === 'manual') continue;
        const run = j.when === 'always' || (j.when === 'on_failure' ? failed : !failed);
        if (!run) {
          j.status = 'skipped';
          continue;
        }
        await this.runJob(p, j);
        if (j.status === 'failed' && !j.allowFailure) failed = true;
      }
    }
    // Manual jobs of a failed pipeline cannot be played any more.
    if (failed) for (const j of p.jobs) if (j.status === 'manual' || j.status === 'created') j.status = 'skipped';
    p.status = this.statusOf(p);
    this.emit();
  }

  private async runJob(p: CiPipeline, j: CiJobRun): Promise<void> {
    const r = this.runner();
    if (!r) {
      j.status = 'failed';
      j.log = 'ERROR: no runner is online (the lab machine is not running)\n';
      return;
    }
    j.status = 'running';
    j.started = Date.now();
    this.emit();
    const base = `/var/lib/lab-ci/${p.id}-${j.id}`;
    const dir = `/builds/${p.repo}`;
    const script = jobScript(p, j.job, dir, `http://git.lab/${p.repo}.git`, `/var/lib/lab-ci/p${p.id}/artifacts`);
    try {
      await r.exec(`mkdir -p /var/lib/lab-ci /builds && cat > ${base}.sh <<'${EOF}'\n${script}${EOF}\nrm -f ${base}.exit; ( sh ${base}.sh > ${base}.log 2>&1; echo $? > ${base}.exit ) </dev/null >/dev/null 2>&1 &`);
      const deadline = Date.now() + (this.o.jobTimeoutMs ?? 20 * 60_000);
      for (;;) {
        await this.sleep(this.o.pollMs ?? 1500);
        if (this.disposed) return;
        const o = await r.exec(`cat ${base}.exit 2>/dev/null; echo '@@DT@@'; tail -c ${LOG_TAIL} ${base}.log 2>/dev/null`);
        const at = o.out.indexOf('@@DT@@');
        const code = o.out.slice(0, at).trim();
        j.log = o.out.slice(at + 7).replace(/^\n/, '');
        this.emit();
        if (code !== '') {
          j.exit = Number(code);
          j.status = j.exit === 0 ? 'success' : 'failed';
          break;
        }
        if (Date.now() > deadline) {
          await r.exec(`pkill -f ${base}.sh 2>/dev/null; true`);
          j.status = 'failed';
          j.log += '\nERROR: Job failed: execution took longer than the timeout\n';
          break;
        }
      }
    } catch (e) {
      j.status = 'failed';
      j.log += `\nERROR: ${(e as Error).message}\n`;
    }
    j.finished = Date.now();
    this.emit();
  }

  facts(): CiScope {
    return {
      pipelines: this.pipelines.map(
        (p): CiPipelineFacts => ({
          id: p.id,
          repo: p.repo,
          ref: p.ref,
          sha: p.sha,
          status: p.status,
          error: p.error,
          jobs: p.jobs.map((j): CiJobFacts => ({ name: j.name, stage: j.stage, status: j.status, exit: j.exit, log: j.log.slice(-4000) })),
        }),
      ),
    };
  }

  /** ci.lab: the pipelines as JSON and the job logs as text, for curl from the machines. */
  handle = (req: HttpRequest): HttpResponse => {
    const enc = (s: string) => new TextEncoder().encode(s);
    const txt = (status: number, s: string): HttpResponse => ({ status, headers: { 'content-type': 'text/plain; charset=utf-8' }, body: enc(s) });
    const js = (v: unknown): HttpResponse => ({ status: 200, headers: { 'content-type': 'application/json' }, body: enc(`${JSON.stringify(v, null, 2)}\n`) });
    const path = req.path.replace(/\/+$/, '');
    if (path === '/api/pipelines') return js(this.facts().pipelines.map((p) => ({ ...p, jobs: p.jobs.map(({ log: _log, ...rest }) => rest) })));
    const m = /^\/(?:api\/)?pipelines\/(\d+)$/.exec(path);
    if (m) {
      const p = this.pipelines.find((x) => x.id === Number(m[1]));
      if (!p) return txt(404, `no pipeline #${m[1]}\n`);
      return txt(200, [`pipeline #${p.id} ${p.repo} ${p.ref} @ ${p.sha.slice(0, 8)}: ${p.status}${p.error ? ` (${p.error})` : ''}`, ...p.jobs.map((j) => `\n── ${j.stage} / ${j.name}: ${j.status}${j.exit !== undefined ? ` (exit ${j.exit})` : ''}\n${j.log}`)].join('\n'));
    }
    return txt(200, `ci.lab — the CI of this tab\n\n${this.pipelines.length ? this.pipelines.map((p) => `  #${p.id}  ${p.status.padEnd(8)} ${p.repo} ${p.ref} ${p.sha.slice(0, 8)}`).join('\n') : '  (no pipelines yet: push a repository with .gitlab-ci.yml to git.lab)'}\n\nGET /api/pipelines, GET /pipelines/<id> (log)\n`);
  };

  dispose(): void {
    this.disposed = true;
    this.off();
  }
}
