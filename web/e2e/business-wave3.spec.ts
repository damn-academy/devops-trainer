import { readFile } from 'node:fs/promises';
import { test, expect } from '@playwright/test';

for (const lang of ['ru', 'en']) test(`business residual fixes at 390px: ${lang}`, async ({ page }) => {
  await page.addInitScript(lang => localStorage.setItem('dt.lang', lang), lang);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/#/lesson/oss.donation');
  const downloaded = page.waitForEvent('download');
  await page.locator('.task-document button').click();
  const rights = await readFile((await (await downloaded).path())!, 'utf8');
  expect(rights.split('\n').filter(line => line.startsWith('| '))).toHaveLength(12);
  const scroll = page.locator('.md-table-scroll').first();
  const frame = page.locator('.md-table-frame').first();
  await expect(frame).toHaveClass(/overflowing/);
  await expect(frame.locator('.md-table-hint')).toBeVisible();
  await expect(scroll).toHaveAttribute('tabindex', '0');
  await expect(scroll).toHaveAttribute('aria-label', /.+/);
  await scroll.scrollIntoViewIfNeeded();
  const first = scroll.locator('tbody tr:first-child td:first-child');
  const before = (await first.boundingBox())!.x;
  await scroll.focus(); await page.keyboard.press('ArrowRight');
  await expect.poll(() => scroll.evaluate(el => el.scrollLeft)).toBeGreaterThan(0);
  await expect(frame.locator('.md-table-hint')).toBeHidden();
  expect(Math.abs((await first.boundingBox())!.x - before)).toBeLessThan(2);
  await scroll.evaluate(el => { el.scrollLeft = 0; });
  await expect(frame.locator('.md-table-hint')).toBeHidden();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await frame.screenshot({ path: `/tmp/business-table-${lang}-390.png` });
  // Widen the container as well: the reading column stays capped on desktop.
  await scroll.evaluate(el => { el.style.width = '2000px'; el.style.maxWidth = 'none'; });
  await expect(frame).not.toHaveClass(/overflowing/);
  await expect(frame.locator('.md-table-hint')).toBeHidden();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/#/lesson/metrics.activation');
  const card = page.locator('textarea[data-template-id]').first();
  await card.fill('Cohort draft: 40/50 = 80%');
  await page.locator('textarea[data-document-id]').fill('Main document draft');
  await page.getByRole('button', { name: lang === 'ru' ? 'Спросить наставника' : 'Ask the tutor', exact: true }).click();
  await page.getByRole('button', { name: lang === 'ru' ? 'Спросить нейросеть' : 'Ask the AI', exact: true }).first().click();
  const preview = page.locator('.external-preview');
  await expect(preview).toHaveValue(/Main document draft/);
  await expect(preview).toHaveValue(/## .+\n\nCohort draft: 40\/50 = 80%/);
  await preview.fill((await preview.inputValue()).replace(/## [^\n]+\n\nCohort draft: 40\/50 = 80%/, ''));
  await expect(preview).not.toHaveValue(/Cohort draft/);
  await page.keyboard.press('Escape');
  await page.goto('/#/lesson/metrics.truth');
  const contractDownload = page.waitForEvent('download');
  await page.locator('.task-document button').click();
  const contract = await readFile((await (await contractDownload).path())!, 'utf8');
  for (const key of ['question', 'version', 'effective_from', 'start_event', 'window_days']) expect(contract).toContain(`\n${key}: `);
  await page.goto('/#/lesson/aicontent.tools');
  await expect(page.locator('.lesson-nav a').last()).toHaveAttribute('href', '#/courses');
});
