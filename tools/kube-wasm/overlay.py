#!/usr/bin/env python3
"""Writes a `go build -overlay` that re-enables the linker's dead-code
elimination of methods.

The Go linker keeps every exported method of every reachable type once any
reachable function looks a method up by a name or index it cannot see at
compile time (reflect.Value.MethodByName(name), Type.Method(i)). Three such
places are reachable in kube-wasm:

  * text/template (*state).evalField: MethodByName(fieldName). Used by
    cobra and kubectl help, kubectl explain and -o go-template.
  * reflect.Value.Methods / reflect.Type.Methods (Go 1.26 iterators),
    reachable because a vendored JSON package embeds reflect.Value in a
    type stored in an interface.
  * go-cmp's type-name printer (patched in patches/0002, not here).

It also keeps heap profiling off the system stack on wasm (see below).

The overlay replaces the text/template lookup with a switch over constant
names: every identifier that follows a '.' in the templates compiled into
the binary. For a constant name the linker keeps only the methods of that
name. Methods not in the list cannot be called from templates; template
fields and map keys are unaffected. The two reflect iterators panic.

usage: overlay.py GOROOT KUBERNETES_SRC OUT_DIR   (prints the overlay.json path)
"""
import json
import os
import re
import sys

goroot, k8s, out = sys.argv[1:4]
os.makedirs(out, exist_ok=True)

# Templates compiled into the binary: cobra's and kubectl's help templates,
# kubectl explain's templates, and cli-runtime's template printer.
TEMPLATE_SOURCES = [
    "vendor/github.com/spf13/cobra",
    "staging/src/k8s.io/kubectl/pkg/util/templates",
    "staging/src/k8s.io/kubectl/pkg/explain/v2",
    "staging/src/k8s.io/cli-runtime/pkg/printers",
]
names = set()
for rel in TEMPLATE_SOURCES:
    for root, _, files in os.walk(os.path.join(k8s, rel)):
        for f in files:
            if f.endswith("_test.go") or not (f.endswith(".go") or f.endswith(".tmpl")):
                continue
            text = open(os.path.join(root, f), encoding="utf-8").read()
            for action in re.findall(r"\{\{.*?\}\}", text, re.S):
                names.update(re.findall(r"\.([A-Z][A-Za-z0-9_]*)", action))
if len(names) < 20:
    sys.exit(f"overlay.py: only {len(names)} template identifiers found; template sources moved?")


def replace(path, old, new):
    text = open(path, encoding="utf-8").read()
    if old not in text:
        sys.exit(f"overlay.py: {old!r} not found in {path}")
    return text.replace(old, new, 1)


def cut_body(text, signature, body):
    i = text.index(signature)
    j = text.index("\n}\n", i)
    return text[:i] + signature + "\n" + body + text[j:]


files = {}
exec_go = os.path.join(goroot, "src/text/template/exec.go")
files[exec_go] = replace(exec_go, "ptr.MethodByName(fieldName)", "kubeWasmMethodByName(ptr, fieldName)")

cases = "".join(f'\tcase "{n}":\n\t\treturn v.MethodByName("{n}")\n' for n in sorted(names))
files[os.path.join(goroot, "src/text/template/kubewasm_methods.go")] = (
    "// Code generated by tools/kube-wasm/overlay.py. DO NOT EDIT.\n\n"
    "package template\n\nimport \"reflect\"\n\n"
    "// kubeWasmMethodByName looks methods up by constant names only, which lets\n"
    "// the linker drop unused methods. See tools/kube-wasm/overlay.py.\n"
    "func kubeWasmMethodByName(v reflect.Value, name string) reflect.Value {\n"
    f"\tswitch name {{\n{cases}\t}}\n\treturn reflect.Value{{}}\n}}\n"
)

panic_body = '\tpanic("reflect: Methods is disabled in kube-wasm builds (see tools/kube-wasm/overlay.py)")'
value_go = os.path.join(goroot, "src/reflect/value.go")
files[value_go] = cut_body(open(value_go).read(), "func (v Value) Methods() iter.Seq2[Method, Value] {", panic_body)
type_go = os.path.join(goroot, "src/reflect/type.go")
files[type_go] = cut_body(open(type_go).read(), "func (t *rtype) Methods() iter.Seq[Method] {", panic_body)

# Heap profiling must not unwind the system stack on wasm. An allocation
# made on g0, such as beforeIdle's timeout event (runtime/lock_js.go) while
# the scheduler looks for work after mcall, can be the sampled one; the
# profiler then unwinds g0, which on wasm cannot be unwound past mcall, and
# the program dies with "invalid runtime symbol table". Such allocations are
# no longer sampled.
malloc_go = os.path.join(goroot, "src/runtime/malloc.go")
files[malloc_go] = replace(malloc_go,
    "\tc.nextSample = nextSample()\n\tmProf_Malloc(mp, x, size)\n",
    "\tc.nextSample = nextSample()\n\tif goarch.IsWasm == 1 && getg() == mp.g0 {\n\t\treturn\n\t}\n\tmProf_Malloc(mp, x, size)\n")

replace_map = {}
for target, content in files.items():
    dst = os.path.join(out, os.path.relpath(target, goroot).replace("/", "_"))
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(content)
    replace_map[target] = dst
path = os.path.join(out, "overlay.json")
with open(path, "w") as fh:
    json.dump({"Replace": replace_map}, fh, indent=1)
print(path)
print(f"overlay.py: {len(names)} template method names", file=sys.stderr)
